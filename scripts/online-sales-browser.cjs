const {chromium}=require('playwright');
const assert=require('node:assert/strict');
async function main(){
 const {createServer}=await import('vite');
 const server=await createServer({server:{host:'127.0.0.1',port:4216,strictPort:true}});await server.listen();
 const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:850},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto('http://127.0.0.1:4216/#/app/online-sales');
  await page.getByRole('button',{name:'New online order'}).click();
  const dlg=page.getByRole('dialog',{name:'New online order'});
  await dlg.getByLabel('Sales channel').click();
  await page.getByRole('listbox',{name:'Sales channel options'}).getByRole('option',{name:'WhatsApp'}).click();
  await dlg.getByLabel('Online customer name').fill('Browser Online Buyer');
  await dlg.getByLabel('Customer mobile').fill('01711442233');
  await dlg.getByLabel('Delivery address').fill('Motijheel Dhaka');
  await dlg.getByLabel('Add online order product').click();
  await page.getByRole('listbox',{name:'Add online order product options'}).getByRole('option',{name:/LED Bulb 12W/}).click();
  await dlg.getByLabel('Order unit row 1').click();
  await page.getByRole('listbox',{name:'Order unit row 1 options'}).getByRole('option',{name:'Box'}).click();
  await dlg.getByLabel('Order quantity row 1').fill('2');
  await dlg.getByLabel('Order payment mode').click();
  await page.getByRole('listbox',{name:'Order payment mode options'}).getByRole('option',{name:'Delivery charge advance'}).click();
  assert.equal(await dlg.getByLabel('Prepaid amount').inputValue(),'100');
  await dlg.getByRole('button',{name:'Save order draft'}).click();
  await dlg.waitFor({state:'hidden'});
  const row=page.locator('div.rounded-lg.border').filter({hasText:'Browser Online Buyer'}).first();
  await row.getByRole('button',{name:'Open'}).click();
  const detail=page.getByRole('dialog',{name:/Online order ON-/});
  await detail.getByText('COD expected:',{exact:false}).waitFor();
  await detail.getByRole('button',{name:'Confirmed'}).click();
  await detail.getByRole('button',{name:'Packed'}).click();
  await detail.getByRole('button',{name:'Assign courier'}).click();
  const courier=page.getByRole('dialog',{name:'Courier action'});
  await courier.getByLabel('Tracking number').fill('TEST-COD-092');
  await courier.getByRole('button',{name:'Save manual preview'}).click();
  await courier.waitFor({state:'hidden'});
  await detail.getByRole('button',{name:'Handed over'}).click();
  await detail.getByRole('button',{name:'In transit'}).click();
  await detail.getByRole('button',{name:'Delivered'}).click();
  await detail.getByRole('button',{name:'Courier COD report'}).click();
  const collected=page.getByRole('dialog',{name:'Courier action'});
  await collected.getByLabel('Courier fee').fill('70');
  await collected.getByRole('button',{name:'Save manual preview'}).click();
  await collected.waitFor({state:'hidden'});
  await detail.getByText('Pending clearing:',{exact:false}).waitFor();
  await detail.getByRole('button',{name:'Record payout'}).click();
  const payout=page.getByRole('dialog',{name:'Courier action'});
  await payout.getByLabel('Courier payout amount').fill('400');
  await payout.getByLabel('Courier payout reference').fill('SETTLEMENT-124');
  await payout.getByRole('button',{name:'Save manual preview'}).click();
  await payout.waitFor({state:'hidden'});
  await detail.getByText('Remitted:',{exact:false}).waitFor();
  await detail.getByRole('button',{name:'Close'}).first().click().catch(async()=>await page.keyboard.press('Escape'));
  await page.getByRole('tab',{name:/SMS Rules/}).click();
  await page.getByLabel('Enable SMS sale_completed').check();
  await page.getByText('no SMS will be sent or billed',{exact:false}).waitFor();
  await page.getByRole('tab',{name:/CRM Leads/}).click();
  await page.getByRole('button',{name:'Add lead'}).click();
  const lead=page.getByRole('dialog',{name:'New CRM lead'});
  await lead.getByLabel('Lead name').fill('Browser lead');
  await lead.getByLabel('Lead phone').fill('01933221100');
  await lead.getByRole('button',{name:'Save lead'}).click();
  await page.getByText('Browser lead',{exact:true}).waitFor();
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.getByRole('button',{name:'New online order'}).isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log('Online sales manual order/COD/CRM/SMS preview desktop+mobile passed');
 }finally{await browser.close();await server.close();}
}
main().catch(err=>{console.error(err);process.exitCode=1});
